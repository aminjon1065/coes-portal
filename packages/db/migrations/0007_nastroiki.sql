-- Настройки, которые хранятся ТОЛЬКО в sys.setting и переменными окружения
-- не переопределяются (docs/03-АРХИТЕКТУРА.md § 5.11). Их меняют из
-- интерфейса, и переменная окружения молча отменяла бы правку.
--
-- Пределы здесь не лежат: их значения по умолчанию объявлены в
-- packages/core/limits.ts двумя наборами — локальным и продуктовым, — и
-- строка в sys.setting нужна только там, где значение переопределяют.

INSERT INTO sys.setting (key, value, is_editable) VALUES
  -- Адрес системы. Абсолютных адресов в данных нет; этот ключ — то самое
  -- единственное место, откуда клиент собирает полный адрес (принцип П-5).
  ('BASE_URL',           'http://localhost:8080', true),
  -- Дополнительные имена, по которым система отвечает при переезде (§ 4 э.).
  ('EXTRA_HOSTNAMES',    '',                      true),
  -- Перенаправлять ли с дополнительных имён на основное.
  ('REDIRECT_TO_BASE',   'false',                 true),
  -- Сессии (docs/05-ДОСТУП.md § 10.3).
  ('SESSION_MAX_HOURS',  '12',                    true),
  ('SESSION_IDLE_MIN',   '60',                    true),
  -- Пароли (§ 10.2).
  ('PASSWORD_MIN_LENGTH',      '12',              true),
  ('PASSWORD_RESET_TTL_MIN',   '60',              true)
ON CONFLICT (key) DO NOTHING;

COMMENT ON COLUMN sys.setting.is_editable IS
  'Изменяется ли настройка на экране «Настройки системы» без перезапуска (docs/03-АРХИТЕКТУРА.md § 5.11).';
