import { existsSync, globSync } from 'node:fs';

/**
 * Входом проверки являются столбцы базы, а база описывается миграциями.
 * Пока миграций нет, столбцов нет — набор входов пуст, и это успех
 * (docs/03-АРХИТЕКТУРА.md § 10), а не повод подключаться к несуществующей базе.
 *
 * Как только миграции появятся, инструмент обязан подключиться к базе и
 * прочитать все текстовые и jsonb-столбцы; отсутствие подключения тогда —
 * ошибка, а не пустой вход.
 */
const MIGRATIONS = 'packages/db/migrations';

const migrations = existsSync(MIGRATIONS)
  ? globSync(`${MIGRATIONS}/*.sql`)
  : [];

if (migrations.length === 0) {
  console.log('check:urls — миграций нет, проверяемых столбцов нет, нарушений: 0');
  process.exit(0);
}

console.error(
  'check:urls — обнаружены миграции, но подключение к базе ещё не реализовано. ' +
    'Реализация подключения — задача этапа 0, следующая за появлением первой миграции. ' +
    'Молчаливый успех здесь запрещён (docs/03-АРХИТЕКТУРА.md § 10).',
);
process.exit(1);
